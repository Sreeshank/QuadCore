import { test,expect } from '@playwright/test';
import path from 'node:path';
import fs from 'node:fs';
test('landing → onboarding → real uploads → verification → discrepancy → assistant → PDF',async({page})=>{
  const errors:string[]=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:/Your taxes/})).toBeVisible();
  await page.screenshot({path:'test-results/landing-desktop.png',fullPage:true});
  await page.getByRole('link',{name:'Get started',exact:true}).first().click();
  await page.getByRole('button',{name:'Enter demo workspace'}).click();
  await expect(page.getByRole('heading',{name:'Let’s make this personal.'})).toBeVisible();
  await page.getByRole('textbox',{name:'Your name'}).fill('Sammer Demo');
  await page.getByRole('button',{name:'Continue',exact:true}).click();
  await page.getByRole('button',{name:'Save & view dashboard'}).click();
  await expect(page.getByRole('heading',{name:'Welcome back, Sammer.'})).toBeVisible();
  await page.getByRole('link',{name:'Upload documents',exact:true}).click();
  const files=['form16.pdf','form26as.pdf','bank-interest.pdf'].map(name=>path.resolve('..','sample_documents',name));
  await page.locator('input[type=file]').setInputFiles(files);
  await expect(page.getByRole('link',{name:/form16.pdf/})).toBeVisible({timeout:60000});
  await expect(page.getByRole('link',{name:/form26as.pdf/})).toBeVisible();
  await expect(page.getByRole('link',{name:/bank-interest.pdf/})).toBeVisible();
  for(const name of ['form16.pdf','form26as.pdf','bank-interest.pdf']){
    await page.getByRole('link',{name:new RegExp(name.replace('.','\\.'))}).click();
    await expect(page.getByRole('heading',{name,exact:true})).toBeVisible();
    await expect(page.getByRole('button',{name:'Confirm reviewed fields'})).toBeEnabled();
    if(name==='form16.pdf')await expect(page.getByRole('textbox',{name:'Gross Salary'})).toHaveValue('850000.00');
    await page.getByRole('button',{name:'Confirm reviewed fields'}).click();
    await page.getByRole('button',{name:'Confirm verification',exact:true}).click();
    await expect(page.getByRole('dialog')).toBeHidden();
    await page.getByRole('link',{name:'All documents',exact:true}).click();
  }
  await page.getByRole('link',{name:'Verification',exact:true}).click();
  await expect(page.getByRole('heading',{name:'TDS discrepancy detected'})).toBeVisible();
  await expect(page.getByText('₹3,000.00',{exact:true})).toBeVisible();
  await page.screenshot({path:'test-results/verification-desktop.png',fullPage:true});
  await page.getByRole('link',{name:/AI assistant/}).click();
  await page.getByRole('button',{name:'Why does my TDS not match?'}).first().click();
  await expect(page.locator('.message-content').filter({hasText:'Difference: INR 3000.00'})).toBeVisible();
  await expect(page.locator('.chat-sources a')).toHaveCount(2);
  await page.getByRole('link',{name:'Overview',exact:true}).click();
  await expect(page.locator('.readiness-ring strong')).toContainText('59');
  await page.screenshot({path:'test-results/dashboard-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Use dark theme'}).click();
  await expect(page.locator('html')).toHaveClass('dark');
  await page.screenshot({path:'test-results/dashboard-dark.png',fullPage:true});
  await page.getByRole('button',{name:'Use light theme'}).click();
  await page.getByRole('link',{name:'Report center',exact:true}).click();
  await page.getByRole('button',{name:'Generate report',exact:true}).click();
  await expect(page.getByRole('button',{name:'Download PDF'}).first()).toBeVisible();
  const download=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download PDF'}).first().click();
  const report=await download;
  await report.saveAs('test-results/browser-readiness-report.pdf');
  expect(fs.readFileSync('test-results/browser-readiness-report.pdf').subarray(0,5).toString()).toBe('%PDF-');
  await page.getByRole('link',{name:'My checklist',exact:true}).click();
  await expect(page.getByRole('heading',{name:'3 of 5 items complete'})).toBeVisible();
  await page.getByRole('button',{name:'Sign out',exact:true}).click();
  await expect(page).toHaveURL(/\/auth/);
  expect(errors).toEqual([]);
});
test('mobile landing and demo navigation fit the viewport',async({page})=>{
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.setViewportSize({width:390,height:844});
  await page.goto('/');
  await expect(page.getByRole('heading',{name:/Your taxes/})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/landing-mobile.png',fullPage:true});
  await page.getByRole('link',{name:'Explore demo'}).click();
  await page.getByRole('button',{name:'Enter demo workspace'}).click();
  await expect(page.getByRole('heading',{name:'Welcome back, Sammer.'})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  await page.screenshot({path:'test-results/dashboard-mobile.png',fullPage:true});
  await page.getByRole('button',{name:'Open navigation'}).click();
  await page.getByRole('link',{name:'My checklist',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Your preparation checklist.'})).toBeVisible();
  await expect(page.locator('.sidebar')).not.toHaveClass(/is-open/);
});

