import {test,expect} from '@playwright/test';
test('manual corrections, saved snapshots, exports, bulk removal and workspace erasure',async({page})=>{
 const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('/');await page.getByRole('link',{name:'Explore demo'}).click();
 await page.getByRole('button',{name:'Enter demo workspace'}).click();
 await expect(page.getByRole('heading',{name:'Welcome back, Sammer.'})).toBeVisible();
 await page.getByRole('link',{name:'Documents',exact:true}).click();
 await page.getByRole('link',{name:/form16.pdf/}).click();
 const deduction=page.locator('.extracted-field').filter({has:page.getByLabel('Deductions',{exact:true})});
 await deduction.getByRole('button',{name:'Remove field'}).click();
 await page.getByRole('dialog').getByRole('button',{name:'Remove field',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeHidden();
 await page.getByRole('button',{name:'Add a missing field'}).click();
 await page.getByRole('combobox',{name:'Field',exact:true}).selectOption('deductions');
 await page.getByLabel('Value',{exact:true}).fill('50000');
 await page.getByLabel('Quote the source evidence').fill('Deductions: INR 50000');
 await page.getByRole('button',{name:'Add unverified field'}).click();
 await expect(page.getByRole('dialog')).toBeHidden();
 await expect(page.getByLabel('Deductions',{exact:true})).toHaveValue('50000.00');
 await page.getByRole('button',{name:'Confirm reviewed fields'}).click();
 await page.getByRole('button',{name:'Confirm verification',exact:true}).click();
 await expect(page.getByRole('dialog')).toBeHidden();
 await deduction.getByRole('button',{name:'Mark for review'}).click();
 await expect(deduction.getByText('Needs your review',{exact:true})).toBeVisible();
 await page.getByRole('link',{name:'Report center',exact:true}).click();
 await page.getByRole('button',{name:'Generate report',exact:true}).click();
 await page.getByRole('button',{name:'View snapshot'}).first().click();
 await expect(page.getByRole('heading',{name:'Saved report snapshot'})).toBeVisible();
 await expect(page.getByText('Preparation score at generation')).toBeVisible();
 await page.screenshot({path:'test-results/report-snapshot.png',fullPage:true});
 await page.getByRole('button',{name:'Close dialog'}).click();
 await page.getByRole('button',{name:'Delete report',exact:true}).first().click();
 await page.getByRole('dialog').getByRole('button',{name:'Delete report',exact:true}).click();
 await expect(page.getByRole('button',{name:'View snapshot'})).toHaveCount(0);
 await page.getByRole('link',{name:'Privacy & activity',exact:true}).click();
 for(const [label,name] of [['Export workspace JSON','TaxReady-workspace.json'],['Export fields CSV','TaxReady-fields.csv']]){
   const pending=page.waitForEvent('download');await page.getByRole('button',{name:label}).click();
   expect((await pending).suggestedFilename()).toBe(name);
 }
 await expect(page.getByText('Field Added',{exact:true})).toBeVisible();
 await page.screenshot({path:'test-results/privacy-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.screenshot({path:'test-results/privacy-mobile.png',fullPage:true});
 await page.setViewportSize({width:1440,height:1000});
 await page.getByRole('link',{name:'Documents',exact:true}).click();
 await page.getByRole('checkbox',{name:'Select all visible documents'}).check();
 await page.getByRole('button',{name:'Delete selected',exact:true}).click();
 await page.getByRole('button',{name:'Delete selected documents',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Your first document is a great first step.'})).toBeVisible();
 await page.getByRole('link',{name:'Privacy & activity',exact:true}).click();
 await page.getByRole('button',{name:'Delete my workspace'}).click();
 await expect(page.getByRole('button',{name:'Permanently delete',exact:true})).toBeDisabled();
 await page.getByPlaceholder('DELETE MY DATA').fill('DELETE MY DATA');
 await page.getByRole('button',{name:'Permanently delete',exact:true}).click();
 await expect(page).toHaveURL(/\/app\/profile/);
 expect(errors).toEqual([]);
});

